const here = path.dirname(fileURLToPath(import.meta.url));
const readJSON = (p) => JSON.parse(fs.readFileSync(p, "utf8"));

function partsOf(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/g, "")
    .replace(/<[^>]+>/g, "|")
    .split("|")
    .map((c) => c.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&nbsp;/g, " ").trim())
    .filter((c) => c);
}

function formWidget(locale) {
  const p = readJSON(path.join(here, "..", "content", locale, "pages", "notices.json"));
  let found = null;
  (function ws(rows) {
    rows.forEach((r) => {
      if (r.kind === "widget" && r.type === "form") found = r;
      if (r.kind === "row") r.cols.forEach((c) => ws(c.children));
    });
  })(p.sections.flatMap((s) => s.rows));
  return found;
}

function privacyOf(parts, startRe) {
  const i = parts.findIndex((c) => startRe.test(c));
  const j = parts.findIndex((c) => /부터 적용됩니다|shall apply from|effective from|take effect on its effective date/i.test(c));
  if (i === -1) return "";
  return parts.slice(i, j === -1 ? undefined : j + 1).join("\n");
}

